
import { useRef, useEffect, useState } from 'react';
import {
  ArrowLeft,
  Bot,
  Heart,
  LoaderCircle,
  Send,
  Sparkles,
  User,
} from 'lucide-react';
import { Link } from 'react-router-dom';
import { apiRequest } from '../lib/api';

type ChatMessage = {
  role: 'user' | 'assistant';
  content: string;
  time: string;
};

const suggestions = [
  'I feel stressed about exams',
  'I have been feeling anxious',
  'I need some motivation',
  'Help me relax today',
];

function getTime() {
  return new Date().toLocaleTimeString([], {
    hour: '2-digit',
    minute: '2-digit',
  });
}

export default function AIChat() {
  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      role: 'assistant',
      content:
        "Hey! 💚 I'm your MindEase companion. How are you feeling today? You can share whatever is on your mind. I'm here to listen without judgment.",
      time: getTime(),
    },
  ]);

  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const bottomRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, loading]);

  async function sendMessage(text?: string) {
    const content = (text ?? input).trim();

    if (!content || loading) return;

    if (content.length > 4000) {
      setError('Please keep your message under 4,000 characters.');
      return;
    }

    const token = localStorage.getItem('mindease_token');

    if (!token) {
      setError('Please log in again to chat with MindEase.');
      return;
    }

    const userMessage: ChatMessage = {
      role: 'user',
      content,
      time: getTime(),
    };

    // Keep the initial greeting in the UI, but don't send it as
    // conversation history because it wasn't generated by the API.
    const previousMessages = messages
      .slice(1)
      .map(({ role, content }) => ({ role, content }));

    const requestMessages = [...previousMessages, {
      role: 'user' as const,
      content,
    }];

    setMessages((current) => [...current, userMessage]);
    setInput('');
    setError('');
    setLoading(true);

    try {
      const result = await apiRequest<{ reply: string }>(
        '/api/chat',
        'POST',
        {
          token,
          body: { messages: requestMessages },
        },
      );

      const reply = result.reply?.trim();

      if (!reply) {
        throw new Error('The assistant returned an empty response.');
      }

      setMessages((current) => [
        ...current,
        {
          role: 'assistant',
          content: reply,
          time: getTime(),
        },
      ]);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : 'Unable to send your message. Please try again.',
      );
    } finally {
      setLoading(false);
      inputRef.current?.focus();
    }
  }

  return (
    <section className="page-section">
      <Link className="back-link" to="/">
        <ArrowLeft size={15} />
        Back to dashboard
      </Link>

      <div
        className="card"
        style={{
          maxWidth: 900,
          margin: '0 auto',
          padding: 0,
          overflow: 'hidden',
        }}
      >
        {/* Chat header */}
        <header
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: 14,
            padding: '20px',
            borderBottom: '1px solid var(--border-color, #e5e7eb)',
          }}
        >
          <div
            className="icon-tile mint"
            style={{
              width: 48,
              height: 48,
              flexShrink: 0,
            }}
          >
            <Bot size={25} />
          </div>

          <div style={{ flex: 1, minWidth: 0 }}>
            <h1 style={{ margin: 0, fontSize: 21 }}>
              MindEase AI
            </h1>
            <p
              className="muted"
              style={{ margin: '5px 0 0', fontSize: 13 }}
            >
              <span style={{ color: '#10b981' }}>● </span>
              Your wellness companion
            </p>
          </div>

          <Sparkles size={22} color="#10b981" />
        </header>

        {/* Welcome message */}
        <div
          style={{
            padding: '14px 20px',
            background: 'var(--surface-secondary, #f0fdf9)',
            display: 'flex',
            alignItems: 'center',
            gap: 10,
          }}
        >
          <Heart size={19} color="#0d9488" />
          <span style={{ fontSize: 13, lineHeight: 1.6 }}>
            A safe space to reflect on your feelings, one conversation
            at a time.
          </span>
        </div>

        {/* Conversation */}
        <div
          aria-live="polite"
          style={{
            height: 'min(52vh, 520px)',
            minHeight: 300,
            overflowY: 'auto',
            padding: '22px 16px',
            display: 'flex',
            flexDirection: 'column',
            gap: 20,
          }}
        >
          {messages.map((message, index) => {
            const isUser = message.role === 'user';

            return (
              <div
                key={`${index}-${message.role}`}
                style={{
                  display: 'flex',
                  justifyContent: isUser ? 'flex-end' : 'flex-start',
                  gap: 9,
                  alignItems: 'flex-start',
                }}
              >
                {!isUser && (
                  <div
                    style={{
                      width: 34,
                      height: 34,
                      flexShrink: 0,
                      borderRadius: 12,
                      background: '#d1fae5',
                      color: '#047857',
                      display: 'grid',
                      placeItems: 'center',
                    }}
                  >
                    <Bot size={19} />
                  </div>
                )}

                <div
                  style={{
                    maxWidth: '82%',
                    minWidth: 0,
                  }}
                >
                  <div
                    style={{
                      padding: '12px 15px',
                      borderRadius: 17,
                      borderTopLeftRadius: isUser ? 17 : 5,
                      borderTopRightRadius: isUser ? 5 : 17,
                      background: isUser
                        ? 'var(--chat-user-bg, #ccfbf1)'
                        : 'var(--chat-ai-bg, #f3f4f6)',
                      color: 'var(--text-primary, #1f2937)',
                      whiteSpace: 'pre-wrap',
                      overflowWrap: 'anywhere',
                      lineHeight: 1.65,
                      fontSize: 14,
                    }}
                  >
                    {message.content}
                  </div>

                  <p
                    className="muted"
                    style={{
                      fontSize: 11,
                      margin: '5px 4px 0',
                      textAlign: isUser ? 'right' : 'left',
                    }}
                  >
                    {isUser ? 'You' : 'MindEase AI'} · {message.time}
                  </p>
                </div>

                {isUser && (
                  <div
                    style={{
                      width: 34,
                      height: 34,
                      flexShrink: 0,
                      borderRadius: 12,
                      background: '#dbeafe',
                      color: '#1d4ed8',
                      display: 'grid',
                      placeItems: 'center',
                    }}
                  >
                    <User size={19} />
                  </div>
                )}
              </div>
            );
          })}

          {loading && (
            <div
              style={{
                display: 'flex',
                alignItems: 'center',
                gap: 10,
                fontSize: 13,
                color: 'var(--text-secondary, #6b7280)',
              }}
            >
              <LoaderCircle
                size={19}
                className="animate-spin"
                color="#0d9488"
              />
              MindEase is thinking...
            </div>
          )}

          <div ref={bottomRef} />
        </div>

        {/* Error message */}
        {error && (
          <div
            role="alert"
            style={{
              margin: '0 16px 12px',
              padding: 12,
              borderRadius: 10,
              background: '#fef2f2',
              color: '#b91c1c',
              fontSize: 13,
            }}
          >
            {error}
          </div>
        )}

        {/* Suggested messages */}
        {messages.length === 1 && !loading && (
          <div style={{ padding: '0 16px 16px' }}>
            <p className="muted" style={{ fontSize: 12, marginBottom: 10 }}>
              You could start with...
            </p>

            <div
              style={{
                display: 'flex',
                flexWrap: 'wrap',
                gap: 8,
              }}
            >
              {suggestions.map((suggestion) => (
                <button
                  key={suggestion}
                  type="button"
                  className="card"
                  onClick={() => sendMessage(suggestion)}
                  style={{
                    padding: '9px 12px',
                    borderRadius: 20,
                    cursor: 'pointer',
                    fontSize: 12,
                  }}
                >
                  {suggestion}
                </button>
              ))}
            </div>
          </div>
        )}

        {/* Message input */}
        <form
          onSubmit={(event) => {
            event.preventDefault();
            void sendMessage();
          }}
          style={{
            display: 'flex',
            alignItems: 'flex-end',
            gap: 10,
            padding: 16,
            borderTop: '1px solid var(--border-color, #e5e7eb)',
          }}
        >
          <textarea
            ref={inputRef}
            value={input}
            onChange={(event) => setInput(event.target.value)}
            onKeyDown={(event) => {
              if (
                event.key === 'Enter' &&
                !event.shiftKey &&
                !event.nativeEvent.isComposing
              ) {
                event.preventDefault();
                void sendMessage();
              }
            }}
            placeholder="Share what's on your mind..."
            aria-label="Your message"
            maxLength={4000}
            rows={2}
            disabled={loading}
            style={{
              flex: 1,
              minWidth: 0,
              resize: 'vertical',
              border: '1px solid var(--border-color, #d1d5db)',
              borderRadius: 14,
              padding: '12px 14px',
              background: 'var(--input-bg, transparent)',
              color: 'var(--text-primary, inherit)',
              font: 'inherit',
              fontSize: 14,
              lineHeight: 1.5,
              outlineOffset: 2,
            }}
          />

          <button
            type="submit"
            aria-label="Send message"
            title="Send message"
            disabled={loading || !input.trim()}
            style={{
              width: 46,
              height: 46,
              flexShrink: 0,
              border: 0,
              borderRadius: 14,
              background: '#0d9488',
              color: '#ffffff',
              display: 'grid',
              placeItems: 'center',
              cursor: loading || !input.trim() ? 'not-allowed' : 'pointer',
              opacity: loading || !input.trim() ? 0.55 : 1,
            }}
          >
            {loading ? (
              <LoaderCircle size={20} className="animate-spin" />
            ) : (
              <Send size={20} />
            )}
          </button>
        </form>

        <p
          className="muted"
          style={{
            textAlign: 'center',
            fontSize: 11,
            padding: '0 16px 16px',
            margin: 0,
          }}
        >
          MindEase offers wellness support, not a clinical diagnosis.
        </p>
      </div>
    </section>
  );
}
